#!/usr/bin/env python3
"""Writes composed-str.wat: two child components that pass strings and lists to each other.

The callee lifts the same functions with every string encoding; the caller lowers them with every
encoding and re-exports each combination, so wasmtime-environ fuses an adapter (with a transcoder)
for every pair of encodings. Used for #47 (multi-memory adapters on Chicory).
"""
from pathlib import Path

ENCODINGS = {"utf8": "utf8", "utf16": "utf16", "compact": "latin1+utf16"}

# cabi_realloc(old, old_size, align, new_size): a bump allocator over pages 0..1 that wraps, so tests
# can make many calls. Shrinking keeps the block; growing copies the old contents (adapters grow
# and shrink their destination while transcoding).
REALLOC = """
    (global $bump (mut i32) (i32.const 0x1000))
    (func (export "realloc") (param $old i32) (param $old-size i32) (param $align i32) (param $size i32) (result i32)
      (local $p i32)
      (if (i32.and (i32.ne (local.get $old) (i32.const 0)) (i32.le_u (local.get $size) (local.get $old-size)))
        (then (return (local.get $old))))
      (local.set $p (i32.and (i32.add (global.get $bump) (i32.sub (local.get $align) (i32.const 1)))
                             (i32.sub (i32.const 0) (local.get $align))))
      (if (i32.gt_u (i32.add (local.get $p) (local.get $size)) (i32.const 0x1F000))
        (then (local.set $p (i32.const 0x1000))))
      (global.set $bump (i32.add (local.get $p) (local.get $size)))
      (if (i32.ne (local.get $old) (i32.const 0))
        (then (memory.copy (local.get $p) (local.get $old) (local.get $old-size))))
      (local.get $p))"""

callee_lifts = "\n".join(
    f'    (func (export "echo-{name}") (param "s" string) (result string)\n'
    f'      (canon lift (core func $ci "echo") (memory $cmem) (realloc $crealloc) string-encoding={enc}))'
    for name, enc in ENCODINGS.items()
)

caller_imports = "\n".join(
    f'    (import "echo-{name}" (func $echo-{name} (param "s" string) (result string)))' for name in ENCODINGS
)
caller_lowers = "\n".join(
    f'    (core func $lower-{b}-{a} (canon lower (func $echo-{a}) (memory $mem) (realloc $realloc) string-encoding={benc}))'
    for b, benc in ENCODINGS.items()
    for a in ENCODINGS
)
caller_core_imports = "\n".join(
    f'      (import "imp" "echo-{b}-{a}" (func $echo-{b}-{a} (param i32 i32 i32)))' for b in ENCODINGS for a in ENCODINGS
)
caller_core_funcs = "\n".join(
    f'      (func (export "echo-{b}-{a}") (param i32 i32) (result i32)\n'
    f'        (call $echo-{b}-{a} (local.get 0) (local.get 1) (i32.const 0x40)) (i32.const 0x40))'
    for b in ENCODINGS
    for a in ENCODINGS
)
caller_imp_instance = "\n".join(
    f'        (export "echo-{b}-{a}" (func $lower-{b}-{a}))' for b in ENCODINGS for a in ENCODINGS
)
caller_lifts = "\n".join(
    f'    (func (export "echo-{b}-{a}") (param "s" string) (result string)\n'
    f'      (canon lift (core func $ui "echo-{b}-{a}") (memory $mem) (realloc $realloc) string-encoding={benc}))'
    for b, benc in ENCODINGS.items()
    for a in ENCODINGS
)
bad_lowers = "\n".join(
    f'    (core func $lower-bad-{bad}-{b} (canon lower (func $bad-{bad}) (memory $mem) (realloc $realloc) string-encoding={benc}))'
    for bad in ("utf8", "utf16")
    for b, benc in ENCODINGS.items()
)
bad_core_imports = "\n".join(
    f'      (import "imp" "bad-{bad}-{b}" (func $bad-{bad}-{b} (param i32)))' for bad in ("utf8", "utf16") for b in ENCODINGS
)
bad_core_funcs = "\n".join(
    f'      (func (export "bad-{bad}-{b}") (result i32) (call $bad-{bad}-{b} (i32.const 0x40)) (i32.const 0x40))'
    for bad in ("utf8", "utf16")
    for b in ENCODINGS
)
bad_imp_instance = "\n".join(
    f'        (export "bad-{bad}-{b}" (func $lower-bad-{bad}-{b}))' for bad in ("utf8", "utf16") for b in ENCODINGS
)
bad_lifts = "\n".join(
    f'    (func (export "bad-{bad}-via-{b}") (result string)\n'
    f'      (canon lift (core func $ui "bad-{bad}-{b}") (memory $mem) (realloc $realloc) string-encoding={benc}))'
    for bad in ("utf8", "utf16")
    for b, benc in ENCODINGS.items()
)
exports = "\n".join(
    [f'  (export "echo-{b}-{a}" (func $caller-i "echo-{b}-{a}"))' for b in ENCODINGS for a in ENCODINGS]
    + [f'  (export "bad-{bad}-via-{b}" (func $caller-i "bad-{bad}-via-{b}"))' for bad in ("utf8", "utf16") for b in ENCODINGS]
    + ['  (export "sum" (func $caller-i "sum"))', '  (export "echo-list" (func $caller-i "echo-list"))']
)

wat = f""";; GENERATED by gen-wat.py; edit that script instead.
;; Two child components with their own memories passing strings and lists (#47). The callee lifts
;; `echo` with every string encoding; the caller lowers it with every encoding and exports each
;; pair as `echo-<caller>-<callee>`, so every fused adapter and transcoder is exercised. `bad-*`
;; make the callee return an invalid utf8 / utf16 string, which the adapter must trap on.
(component
  (component $callee
    (core module $cm
      (memory (export "mem") 2)
      (data (i32.const 0x100) "\\ff\\fe")       ;; invalid UTF-8
      (data (i32.const 0x110) "\\00\\d8")       ;; UTF-16LE lone high surrogate{REALLOC}
      ;; string results go through a return area: (ptr, len)
      (func (export "echo") (param i32 i32) (result i32)
        (i32.store (i32.const 0x10) (local.get 0)) (i32.store (i32.const 0x14) (local.get 1)) (i32.const 0x10))
      (func (export "bad-utf8") (result i32)
        (i32.store (i32.const 0x20) (i32.const 0x100)) (i32.store (i32.const 0x24) (i32.const 2)) (i32.const 0x20))
      (func (export "bad-utf16") (result i32)
        (i32.store (i32.const 0x28) (i32.const 0x110)) (i32.store (i32.const 0x2c) (i32.const 1)) (i32.const 0x28))
      (func (export "sum") (param $p i32) (param $n i32) (result i32)
        (local $s i32)
        (block $done (loop $next
          (br_if $done (i32.eqz (local.get $n)))
          (local.set $s (i32.add (local.get $s) (i32.load (local.get $p))))
          (local.set $p (i32.add (local.get $p) (i32.const 4)))
          (local.set $n (i32.sub (local.get $n) (i32.const 1)))
          (br $next)))
        (local.get $s))
      (func (export "echo-list") (param i32 i32) (result i32)
        (i32.store (i32.const 0x30) (local.get 0)) (i32.store (i32.const 0x34) (local.get 1)) (i32.const 0x30)))
    (core instance $ci (instantiate $cm))
    (alias core export $ci "mem" (core memory $cmem))
    (alias core export $ci "realloc" (core func $crealloc))
{callee_lifts}
    (func (export "bad-utf8") (result string)
      (canon lift (core func $ci "bad-utf8") (memory $cmem) string-encoding=utf8))
    (func (export "bad-utf16") (result string)
      (canon lift (core func $ci "bad-utf16") (memory $cmem) string-encoding=utf16))
    (func (export "sum") (param "l" (list u32)) (result u32)
      (canon lift (core func $ci "sum") (memory $cmem) (realloc $crealloc)))
    (func (export "echo-list") (param "l" (list u32)) (result (list u32))
      (canon lift (core func $ci "echo-list") (memory $cmem) (realloc $crealloc))))
  (instance $callee-i (instantiate $callee))

  (component $caller
{caller_imports}
    (import "bad-utf8" (func $bad-utf8 (result string)))
    (import "bad-utf16" (func $bad-utf16 (result string)))
    (import "sum" (func $sum (param "l" (list u32)) (result u32)))
    (import "echo-list" (func $echo-list (param "l" (list u32)) (result (list u32))))
    (core module $mm
      (memory (export "mem") 2){REALLOC})
    (core instance $mi (instantiate $mm))
    (alias core export $mi "mem" (core memory $mem))
    (alias core export $mi "realloc" (core func $realloc))
{caller_lowers}
{bad_lowers}
    (core func $lower-sum (canon lower (func $sum) (memory $mem) (realloc $realloc)))
    (core func $lower-echo-list (canon lower (func $echo-list) (memory $mem) (realloc $realloc)))
    (core module $user
{caller_core_imports}
{bad_core_imports}
      (import "imp" "sum" (func $sum (param i32 i32) (result i32)))
      (import "imp" "echo-list" (func $echo-list (param i32 i32 i32)))
{caller_core_funcs}
{bad_core_funcs}
      (func (export "sum") (param i32 i32) (result i32) (call $sum (local.get 0) (local.get 1)))
      (func (export "echo-list") (param i32 i32) (result i32)
        (call $echo-list (local.get 0) (local.get 1) (i32.const 0x40)) (i32.const 0x40)))
    (core instance $ui (instantiate $user
      (with "imp" (instance
{caller_imp_instance}
{bad_imp_instance}
        (export "sum" (func $lower-sum))
        (export "echo-list" (func $lower-echo-list))))))
{caller_lifts}
{bad_lifts}
    (func (export "sum") (param "l" (list u32)) (result u32)
      (canon lift (core func $ui "sum") (memory $mem) (realloc $realloc)))
    (func (export "echo-list") (param "l" (list u32)) (result (list u32))
      (canon lift (core func $ui "echo-list") (memory $mem) (realloc $realloc))))
  (instance $caller-i (instantiate $caller
{chr(10).join(f'    (with "echo-{n}" (func $callee-i "echo-{n}"))' for n in ENCODINGS)}
    (with "bad-utf8" (func $callee-i "bad-utf8"))
    (with "bad-utf16" (func $callee-i "bad-utf16"))
    (with "sum" (func $callee-i "sum"))
    (with "echo-list" (func $callee-i "echo-list"))))
{exports}
)
"""
Path(__file__).with_name("composed-str.wat").write_text(wat)
