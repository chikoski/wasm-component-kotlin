package com.example.wasicli

import com.example.wasicli.exports.wasi.cli.run.run
import wasm2kt.wasi.runWasiCommand
import wasm2kt.wasi.wasi03Imports
import java.io.ByteArrayOutputStream
import java.nio.file.Files

fun main() {
    val workDir = Files.createTempDirectory("wasm2kt-wasi-cli")
    try {
        Files.writeString(
            workDir.resolve("input.txt"),
            "first item\n\nsecond item\nthird item\n",
        )

        val stdoutBuf = ByteArrayOutputStream()
        val stderrBuf = ByteArrayOutputStream()
        val wasiImports = wasi03Imports {
            args("wasi-cli", "input.txt", "output.txt")
            env("TAG" to "cli")
            stdin("generated by 07-wasi-cli")
            stdout = stdoutBuf
            stderr = stderrBuf
            mounts {
                readWrite("/work", workDir)
            }
        }

        val exitCode = runWasiCommand {
            withSessionBlocking(WasiCliComponent, wasiImports) {
                run()
            }
        }

        val stdoutText = stdoutBuf.toString(Charsets.UTF_8).trimEnd()
        val stderrText = stderrBuf.toString(Charsets.UTF_8).trimEnd()
        val outputText = Files.readString(workDir.resolve("output.txt")).trimEnd()

        println("exitCode = $exitCode")
        println("stdout = $stdoutText")
        if (stderrText.isNotEmpty()) {
            println("stderr = $stderrText")
        }
        println("outputFile =")
        println(outputText)
    } finally {
        workDir.toFile().deleteRecursively()
    }
}
