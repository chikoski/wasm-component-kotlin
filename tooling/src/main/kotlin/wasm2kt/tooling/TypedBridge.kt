package wasm2kt.tooling

import wasm2kt.ast.HandleKind
import wasm2kt.ast.WitFunction
import wasm2kt.ast.WitResolve
import wasm2kt.ast.WitTypeDefKind
import wasm2kt.ast.WitTypeOwner
import wasm2kt.ast.WitTypeRef
import wasm2kt.ast.WitWorld
import wasm2kt.ast.WitWorldItem
import java.nio.file.Files
import java.nio.file.Path
import java.util.concurrent.TimeUnit

/**
 * The typed Wasmtime bridge (ADR-0015, ADR-0016): one Cargo crate, and one native library, for all
 * the components of a project. For each component it generates Rust types for the WIT types (with
 * Wasmtime's `ComponentType` / `Lift` / `Lower` derives and `flags!`), typed calls of the exports
 * (`Func::typed`) and typed host imports (`func_wrap`), reading and writing the binary format
 * (ADR-0015). The session machinery, C ABI and JNI entry points come from `wasm2kt-bridge-core`,
 * which the crate carries in `core/`; the library exports the same functions as the generic bridge,
 * and calls generically what the generator does not cover.
 */
object TypedBridge {
    /** A component of the bridge: the ID its bindings open sessions with (`--bridge-id`), and its WIT. */
    class Component(val id: String, val resolve: WitResolve, val worldName: String? = null)

    /** The generic bridge's library name; a typed bridge uses it too, so it replaces the generic one as is. */
    const val DEFAULT_LIBRARY = "wasm2kt_wasmtime_bridge"

    /**
     * Writes the crate into [crateDir]. [libraryName] names the library (`lib<name>.so`); another name
     * lets it share Cargo's target directory with the generic bridge, e.g. in tests.
     */
    fun generateCrate(components: List<Component>, crateDir: Path, libraryName: String = DEFAULT_LIBRARY) {
        require(Regex("[a-z_][a-z0-9_]*").matches(libraryName)) { "Invalid library name '$libraryName'" }
        require(components.isNotEmpty()) { "A typed bridge needs at least one component" }
        val ids = components.map { it.id }
        require(ids.distinct().size == ids.size) { "Component IDs must be unique: ${ids.groupBy { it }.filterValues { it.size > 1 }.keys}" }
        ids.forEach { require(it.isNotEmpty() && '"' !in it && '\\' !in it) { "Invalid component ID '$it'" } }

        Files.createDirectories(crateDir.resolve("src"))
        copyCore(crateDir.resolve("core"))
        write(crateDir.resolve("Cargo.toml"), cargoToml(libraryName))
        write(crateDir.resolve("Cargo.lock"), resource("Cargo.lock"))
        val modules = components.mapIndexed { i, c -> "c$i" to c }
        for ((module, c) in modules) {
            write(crateDir.resolve("src/$module.rs"), RustComponent(c).generate())
        }
        write(
            crateDir.resolve("src/lib.rs"),
            buildString {
                appendLine("//! Typed Wasmtime bridge generated by wasm2kt (ADR-0016). Do not edit.")
                appendLine()
                for ((module, c) in modules) appendLine("mod $module; // ${c.id}")
                appendLine()
                append("wasm2kt_bridge_core::export_bridge!(&[")
                append(modules.joinToString(", ") { (module, _) -> "&$module::Component" })
                appendLine("]);")
            },
        )
    }

    /**
     * Runs `cargo build --release` in [crateDir] (for [target], or the host) and returns the library.
     * [targetDir] is Cargo's target directory; sharing it between builds avoids compiling Wasmtime
     * again. Fails if `cargo` is missing: a build that asks for the typed bridge needs it (ADR-0015).
     */
    fun cargoBuild(
        crateDir: Path,
        targetDir: Path? = null,
        target: String? = null,
        cargo: String = "cargo",
        libraryName: String = DEFAULT_LIBRARY,
    ): Path {
        val command = buildList {
            add(cargo); add("build"); add("--release")
            add("--manifest-path"); add(crateDir.resolve("Cargo.toml").toAbsolutePath().toString())
            if (targetDir != null) { add("--target-dir"); add(targetDir.toAbsolutePath().toString()) }
            if (target != null) { add("--target"); add(target) }
        }
        val process = try {
            ProcessBuilder(command).redirectErrorStream(true).start()
        } catch (e: java.io.IOException) {
            throw IllegalStateException("The typed bridge needs cargo, which was not found ('$cargo'): install Rust (https://rustup.rs)", e)
        }
        val output = process.inputStream.bufferedReader().readText()
        if (!process.waitFor(2, TimeUnit.HOURS) || process.exitValue() != 0) {
            throw IllegalStateException("cargo build of the typed bridge failed:\n$output")
        }
        val dir = (targetDir ?: crateDir.resolve("target")).let { if (target != null) it.resolve(target) else it }.resolve("release")
        return dir.resolve(libraryFileName(target, libraryName))
    }

    /** `lib<name>.so` / `.dylib` / `<name>.dll` for [target] (the host if null). */
    fun libraryFileName(target: String? = null, libraryName: String = DEFAULT_LIBRARY): String {
        val os = target ?: System.getProperty("os.name").lowercase()
        return when {
            "windows" in os || os.startsWith("win") -> "$libraryName.dll"
            "apple" in os || "darwin" in os || "mac" in os -> "lib$libraryName.dylib"
            else -> "lib$libraryName.so"
        }
    }

    private const val RESOURCES = "/wasm2kt/bridge-core/"

    private fun resource(name: String): String =
        requireNotNull(TypedBridge::class.java.getResourceAsStream(RESOURCES + name)) { "Missing tooling resource $RESOURCES$name" }
            .use { String(it.readBytes(), Charsets.UTF_8) }

    private fun copyCore(dir: Path) {
        for (name in resource("files.txt").lines().filter { it.isNotBlank() }) {
            write(dir.resolve(name), resource("core/$name"))
        }
    }

    private fun write(path: Path, content: String) {
        Files.createDirectories(path.parent)
        // Unchanged files keep their timestamps, so cargo does not rebuild them.
        if (Files.exists(path) && Files.readString(path) == content) return
        Files.writeString(path, content)
    }

    private fun cargoToml(libraryName: String): String {
        // The package and library are named like the generic bridge so a typed bridge replaces it
        // as is (and the generic bridge's Cargo.lock, shipped with tooling, applies unchanged).
        val generic = resource("Cargo.toml")
        val lints = generic.substringAfter("[workspace.lints.clippy]").substringBefore("\n[")
        return """
            |# Typed Wasmtime bridge generated by wasm2kt (ADR-0016). Do not edit.
            |[workspace]
            |members = [".", "core"]
            |resolver = "2"
            |
            |[workspace.lints.clippy]$lints
            |
            |[package]
            |name = "wasm2kt-wasmtime-bridge"
            |version = "0.1.0"
            |edition = "2021"
            |publish = false
            |
            |[lib]
            |name = "$libraryName"
            |crate-type = ["cdylib"]
            |
            |[dependencies]
            |wasm2kt-bridge-core = { path = "core" }
            |""".trimMargin()
    }
}

/** The Rust module of one component of a typed bridge. */
private class RustComponent(private val component: TypedBridge.Component) {
    private val resolve = component.resolve
    private val world: WitWorld = run {
        val worlds = component.worldName?.let { name -> resolve.worlds.filter { it.name == name } } ?: resolve.worlds
        require(worlds.size == 1) {
            if (worlds.isEmpty()) "No world '${component.worldName}' in component '${component.id}'"
            else "Component '${component.id}' defines several worlds (${worlds.joinToString { it.name }}); choose one"
        }
        worlds.single()
    }

    /** Interfaces the world imports and exports, with their keys (ADR-0011). */
    private val imported: Map<Int, String> = interfaces(world.imports)
    private val exported: Map<Int, String> = interfaces(world.exports)

    private fun interfaces(items: Map<String, WitWorldItem>): Map<Int, String> =
        items.mapNotNull { (key, item) -> (item as? WitWorldItem.InterfaceRef)?.let { it.id to interfaceKey(it.id, key) } }.toMap()

    /** `ns:pkg/iface@1.0` for package interfaces, the world's name for inline ones (ADR-0011). */
    private fun interfaceKey(id: Int, worldKey: String): String {
        val iface = resolve.interfaces[id]
        val pkg = iface.`package`?.let { resolve.packages.getOrNull(it)?.name }
        if (iface.name == null || pkg == null) return worldKey
        val ns = pkg.substringBefore(':')
        val rest = pkg.substringAfter(':')
        val version = rest.substringAfter('@', "")
        return "$ns:${rest.substringBefore('@')}/${iface.name}" + (if (version.isEmpty()) "" else "@$version")
    }

    private val typeDefs = StringBuilder()
    private val definedTypes = mutableSetOf<Int>()

    private class Unsupported(message: String) : Exception(message)

    fun generate(): String {
        val exports = StringBuilder()
        val exportArms = StringBuilder()
        val importArms = StringBuilder()
        val skipped = mutableListOf<String>()
        var n = 0
        for ((key, fn, iface) in functions(world.exports, exported)) {
            context = Context(iface, export = true)
            try {
                exports.append(exportCall("E$n", key, fn))
                exportArms.append("            \"${esc(key)}\" => Box::new(E$n(func.typed(store)?)),\n")
                n++
            } catch (e: Unsupported) {
                skipped += "export $key: ${e.message}"
            }
        }
        for ((key, fn, iface) in functions(world.imports, imported)) {
            context = Context(iface, export = false)
            try {
                importArms.append(importLink(key, fn))
            } catch (e: Unsupported) {
                skipped += "import $key: ${e.message}"
            }
        }
        return buildString {
            appendLine("//! Typed calls of component '${component.id}' (world '${world.name}'), generated by wasm2kt. Do not edit.")
            if (skipped.isNotEmpty()) {
                appendLine("//!")
                appendLine("//! Called through the generic path:")
                skipped.forEach { appendLine("//! * $it") }
            }
            appendLine("#![allow(clippy::all, dead_code, unreachable_code, unused_braces, unused_imports, unused_mut, unused_variables, non_camel_case_types)]")
            appendLine()
            appendLine("use wasm2kt_bridge_core::typed::*;")
            appendLine("use wasm2kt_bridge_core::wasmtime;")
            appendLine("use wasmtime::component::{flags, ComponentType, Lift, Lower};")
            appendLine()
            appendLine("pub struct Component;")
            appendLine()
            appendLine("impl TypedComponent for Component {")
            appendLine("    fn id(&self) -> &'static str {")
            appendLine("        \"${esc(component.id)}\"")
            appendLine("    }")
            appendLine()
            appendLine("    fn link_import(&self, inst: &mut LinkerInstance<'_, StoreData>, name: &str, key: &ImportKey) -> Result<bool> {")
            appendLine("        let k = key.name().into_owned();")
            appendLine("        let key = key.clone();")
            appendLine("        match k.as_str() {")
            append(importArms)
            appendLine("            _ => return Ok(false),")
            appendLine("        }")
            appendLine("        Ok(true)")
            appendLine("    }")
            appendLine()
            appendLine("    fn export(&self, name: &str, func: Func, store: &Store<StoreData>) -> Result<Option<Box<dyn TypedExport>>> {")
            appendLine("        Ok(Some(match name {")
            append(exportArms)
            appendLine("            _ => return Ok(None),")
            appendLine("        }))")
            appendLine("    }")
            appendLine("}")
            append(exports)
            append(typeDefs)
        }
    }

    /** Root functions and interface functions (with their interface), by their keys (ADR-0011). */
    private fun functions(items: Map<String, WitWorldItem>, interfaces: Map<Int, String>): List<Triple<String, WitFunction, Int?>> = buildList {
        for ((_, item) in items) {
            if (item is WitWorldItem.FunctionItem) add(Triple(item.function.name, item.function, null))
        }
        for ((id, key) in interfaces) {
            for ((_, fn) in resolve.interfaces[id].functions) add(Triple("$key#${fn.name}", fn, id))
        }
    }

    private fun signature(fn: WitFunction): Pair<List<WitTypeRef>, WitTypeRef?> {
        if (fn.results.size > 1) throw Unsupported("several results")
        if (fn.params.size > 16) throw Unsupported("more than 16 parameters")
        return fn.params.map { it.type } to fn.results.singleOrNull()?.type
    }

    private fun tupleType(types: List<String>): String = if (types.isEmpty()) "()" else types.joinToString(", ", "(", ",)")

    private fun exportCall(name: String, key: String, fn: WitFunction): String {
        val (params, result) = signature(fn)
        val paramTypes = params.map { rustType(it) }
        val resultType = result?.let { rustType(it) }
        val counter = Counter()
        return buildString {
            appendLine()
            appendLine("/// `${esc(key)}`")
            appendLine("struct $name(TypedFunc<${tupleType(paramTypes)}, ${tupleType(listOfNotNull(resultType))}>);")
            appendLine()
            appendLine("impl TypedExport for $name {")
            appendLine("    fn call(&self, store: &mut Store<StoreData>, args: &[u8]) -> Result<Vec<u8>> {")
            appendLine("        let params = {")
            appendLine("            let cx = &mut store.as_context_mut();")
            appendLine("            let r = &mut Reader::new(args);")
            params.forEachIndexed { i, p -> appendLine("            let a$i = ${read(p, counter)};") }
            appendLine("            r.finish().context(\"Invalid arguments for '${esc(key)}'\")?;")
            appendLine("            ${tupleType(params.indices.map { "a$it" })}")
            appendLine("        };")
            appendLine("        let results = self.0.call(&mut *store, params)?;")
            appendLine("        let mut out = Vec::new();")
            if (result != null) {
                appendLine("        {")
                appendLine("            let cx = &mut store.as_context_mut();")
                appendLine("            let w = &mut out;")
                appendLine("            ${write(result, "&results.0", counter)}")
                appendLine("        }")
            }
            appendLine("        Ok(out)")
            appendLine("    }")
            appendLine("}")
        }
    }

    private fun importLink(key: String, fn: WitFunction): String {
        val (params, result) = signature(fn)
        val paramTypes = params.map { rustType(it) }
        val resultType = result?.let { rustType(it) }
        val counter = Counter()
        return buildString {
            appendLine("            \"${esc(key)}\" => inst.func_wrap(")
            appendLine("                name,")
            appendLine("                move |mut ctx: StoreContextMut<'_, StoreData>, ${tupleType(params.indices.map { "a$it" })}: ${tupleType(paramTypes)}| -> Result<${tupleType(listOfNotNull(resultType))}> {")
            appendLine("                    let mut args = Vec::new();")
            appendLine("                    {")
            appendLine("                        let cx = &mut ctx;")
            appendLine("                        let w = &mut args;")
            params.forEachIndexed { i, p -> appendLine("                        ${write(p, "&a$i", counter)}") }
            appendLine("                    }")
            appendLine("                    let response = call_host(&mut ctx, &key, &args)?;")
            appendLine("                    let cx = &mut ctx;")
            appendLine("                    let r = &mut Reader::new(&response);")
            if (result != null) {
                appendLine("                    let result = ${read(result, counter)};")
            }
            appendLine("                    r.finish().context(\"Invalid results from host import '${esc(key)}'\")?;")
            appendLine("                    Ok(${if (result != null) "(result,)" else "()"})")
            appendLine("                },")
            appendLine("            )?,")
        }
    }

    // ------------------------------------------------------------------ types

    private class Counter {
        private var n = 0
        fun next(): String = "v${n++}"
    }

    private fun resolveAlias(ref: WitTypeRef): WitTypeRef {
        var r = ref
        while (r is WitTypeRef.Id) {
            val kind = resolve.types[r.index].kind
            if (kind is WitTypeDefKind.TypeAlias) r = kind.type else break
        }
        return r
    }

    private fun resourceId(id: Int): Int {
        var r = id
        while (true) {
            val kind = resolve.types[r].kind
            if (kind is WitTypeDefKind.TypeAlias && kind.type is WitTypeRef.Id) r = (kind.type as WitTypeRef.Id).index else return r
        }
    }

    private val prims = mapOf(
        "u8" to "u8", "s8" to "i8", "u16" to "u16", "s16" to "i16", "u32" to "u32", "s32" to "i32",
        "u64" to "u64", "s64" to "i64", "f32" to "f32", "f64" to "f64",
    )

    private fun primitive(name: String): String = prims[name] ?: when (name) {
        "bool" -> "bool"
        "char" -> "char"
        "string" -> "String"
        else -> throw Unsupported("type $name")
    }

    private fun rustType(ref: WitTypeRef): String = when (val r = resolveAlias(ref)) {
        is WitTypeRef.Primitive -> primitive(r.name)
        is WitTypeRef.Id -> when (val kind = resolve.types[r.index].kind) {
            is WitTypeDefKind.ListType -> "Vec<${rustType(kind.type)}>"
            is WitTypeDefKind.OptionType -> "Option<${rustType(kind.type)}>"
            is WitTypeDefKind.ResultType -> "Result<${kind.ok?.let { rustType(it) } ?: "()"}, ${kind.err?.let { rustType(it) } ?: "()"}>"
            is WitTypeDefKind.Tuple -> {
                if (kind.types.size > 16) throw Unsupported("tuple of more than 16 elements")
                tupleType(kind.types.map { rustType(it) })
            }
            is WitTypeDefKind.Handle -> { resourceKind(kind.resourceId); "ResourceAny" }
            is WitTypeDefKind.Record, is WitTypeDefKind.Variant, is WitTypeDefKind.Enum, is WitTypeDefKind.Flags -> {
                define(r.index)
                "T${r.index}"
            }
            is WitTypeDefKind.FutureType, is WitTypeDefKind.StreamType -> throw Unsupported("async types are not supported by the Wasmtime bridge")
            else -> throw Unsupported("type $kind")
        }
    }

    /** The interface and direction of the function being generated; null inside named types. */
    private data class Context(val iface: Int?, val export: Boolean)

    private var context: Context? = null

    /** The host payload key of a host resource, or null for a component-defined one. */
    private fun resourceKind(handleTarget: Int): String? {
        val id = resourceId(handleTarget)
        val def = resolve.types[id]
        val name = def.name ?: throw Unsupported("unnamed resource")
        val owner: WitTypeOwner? = def.owner
        return when {
            owner?.`interface` != null -> {
                val iface = owner.`interface`!!
                val imp = imported[iface]
                val exp = exported[iface]
                when {
                    // The world imports the interface and exports its own version of it: the
                    // resource is the component's in the exported functions of that interface.
                    imp != null && exp != null -> when (context) {
                        null -> throw Unsupported("resource '$name' of an interface the world both imports and exports, inside a type")
                        Context(iface, export = true) -> null
                        else -> "$imp#$name"
                    }
                    imp != null -> "$imp#$name"
                    exp != null -> null
                    else -> throw Unsupported("resource '$name' of an interface outside the world")
                }
            }
            owner?.world != null -> name
            else -> throw Unsupported("resource '$name' without an owner")
        }
    }

    private fun read(ref: WitTypeRef, c: Counter): String = when (val r = resolveAlias(ref)) {
        is WitTypeRef.Primitive -> when (r.name) {
            "bool" -> "read_bool(r)?"
            "char" -> "read_char(r)?"
            "string" -> "read_string(r)?"
            else -> "read_prim::<${primitive(r.name)}>(r)?"
        }
        is WitTypeRef.Id -> when (val kind = resolve.types[r.index].kind) {
            is WitTypeDefKind.ListType -> {
                val elem = resolveAlias(kind.type)
                if (elem is WitTypeRef.Primitive && elem.name == "u8") "read_bytes(r)?"
                else if (elem is WitTypeRef.Primitive && elem.name in prims) "read_prim_list::<${prims.getValue(elem.name)}>(r)?"
                else {
                    val v = c.next()
                    "{ let n = read_len(r)?; let mut $v = Vec::with_capacity(n.min(r.remaining())); for _ in 0..n { $v.push(${read(kind.type, c)}); } $v }"
                }
            }
            is WitTypeDefKind.OptionType -> "if read_tag(r, \"option\")? { Some(${read(kind.type, c)}) } else { None }"
            is WitTypeDefKind.ResultType ->
                "if read_tag(r, \"result\")? { Err(${kind.err?.let { read(it, c) } ?: "()"}) } else { Ok(${kind.ok?.let { read(it, c) } ?: "()"}) }"
            is WitTypeDefKind.Tuple -> tupleType(kind.types.map { read(it, c) })
            is WitTypeDefKind.Handle -> {
                val host = resourceKind(kind.resourceId)
                when {
                    host != null && kind.kind == HandleKind.OWN -> "read_own_host(r, host_payload(cx, \"${esc(host)}\")?, cx)?"
                    host != null -> "read_borrow_host(r, host_payload(cx, \"${esc(host)}\")?, cx)?"
                    kind.kind == HandleKind.OWN -> "read_own_guest(r, cx)?"
                    else -> "read_borrow_guest(r, cx)?"
                }
            }
            is WitTypeDefKind.Record, is WitTypeDefKind.Variant, is WitTypeDefKind.Enum, is WitTypeDefKind.Flags -> {
                define(r.index)
                "read_t${r.index}(r, cx)?"
            }
            else -> throw Unsupported("type $kind")
        }
    }

    /** Statements writing the value of [value], an expression of type `&T`. */
    private fun write(ref: WitTypeRef, value: String, c: Counter): String = when (val r = resolveAlias(ref)) {
        is WitTypeRef.Primitive -> when (r.name) {
            "bool" -> "write_bool(w, *$value);"
            "char" -> "write_char(w, *$value);"
            "string" -> "write_string(w, $value)?;"
            else -> "write_prim(w, *$value);"
        }
        is WitTypeRef.Id -> when (val kind = resolve.types[r.index].kind) {
            is WitTypeDefKind.ListType -> {
                val elem = resolveAlias(kind.type)
                if (elem is WitTypeRef.Primitive && elem.name == "u8") "write_bytes(w, $value)?;"
                else if (elem is WitTypeRef.Primitive && elem.name in prims) "write_prim_list(w, $value)?;"
                else {
                    val v = c.next()
                    "write_len(w, ($value).len())?; for $v in ($value).iter() { ${write(kind.type, v, c)} }"
                }
            }
            is WitTypeDefKind.OptionType -> {
                val v = c.next()
                "match $value { Some($v) => { w.push(1); ${write(kind.type, v, c)} } None => w.push(0) }"
            }
            is WitTypeDefKind.ResultType -> {
                val ok = c.next()
                val err = c.next()
                "match $value { Ok($ok) => { w.push(0); ${kind.ok?.let { write(it, ok, c) } ?: ""} } Err($err) => { w.push(1); ${kind.err?.let { write(it, err, c) } ?: ""} } }"
            }
            is WitTypeDefKind.Tuple -> {
                val v = c.next()
                "{ let $v = $value; ${kind.types.withIndex().joinToString(" ") { (i, t) -> write(t, "&$v.$i", c) }} }"
            }
            is WitTypeDefKind.Handle -> { resourceKind(kind.resourceId); "write_resource(w, *$value, cx)?;" }
            is WitTypeDefKind.Record, is WitTypeDefKind.Variant, is WitTypeDefKind.Enum, is WitTypeDefKind.Flags -> {
                define(r.index)
                "write_t${r.index}(w, $value, cx)?;"
            }
            else -> throw Unsupported("type $kind")
        }
    }

    /** Defines the Rust type `T<index>` and its read / write functions, once. */
    private fun define(index: Int) {
        if (index in definedTypes) return
        val def = resolve.types[index]
        val name = "T$index"
        val witName = def.name ?: "type-$index"
        val c = Counter()
        // Build into a local buffer first: nested types append their own definitions as they go.
        val out = StringBuilder()
        definedTypes += index
        val outer = context
        context = null
        try {
            when (val kind = def.kind) {
                is WitTypeDefKind.Record -> {
                    val fields = kind.fields.map { Triple(it.name, rustType(it.type), it.type) }
                    out.appendLine()
                    out.appendLine("/// WIT `record $witName`")
                    out.appendLine("#[derive(ComponentType, Lift, Lower)]")
                    out.appendLine("#[component(record)]")
                    out.appendLine("pub struct $name {")
                    fields.forEachIndexed { i, (n, t, _) -> out.appendLine("    #[component(name = \"${esc(n)}\")]\n    pub f$i: $t,") }
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn read_t$index(r: &mut Reader<'_>, cx: &mut Cx<'_>) -> Result<$name> {")
                    fields.forEachIndexed { i, (_, _, t) -> out.appendLine("    let f$i = ${read(t, c)};") }
                    out.appendLine("    Ok($name { ${fields.indices.joinToString(", ") { "f$it" }} })")
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn write_t$index(w: &mut Vec<u8>, v: &$name, cx: &mut Cx<'_>) -> Result<()> {")
                    fields.forEachIndexed { i, (_, _, t) -> out.appendLine("    ${write(t, "&v.f$i", c)}") }
                    out.appendLine("    Ok(())")
                    out.appendLine("}")
                }
                is WitTypeDefKind.Variant -> {
                    val count = kind.cases.size
                    val cases = kind.cases.map { it.name to it.type?.let { t -> rustType(t) to t } }
                    out.appendLine()
                    out.appendLine("/// WIT `variant $witName`")
                    out.appendLine("#[derive(ComponentType, Lift, Lower)]")
                    out.appendLine("#[component(variant)]")
                    out.appendLine("pub enum $name {")
                    cases.forEachIndexed { i, (n, p) -> out.appendLine("    #[component(name = \"${esc(n)}\")]\n    C$i${p?.let { "(${it.first})" } ?: ""},") }
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn read_t$index(r: &mut Reader<'_>, cx: &mut Cx<'_>) -> Result<$name> {")
                    out.appendLine("    Ok(match read_discriminant(r, $count)? {")
                    cases.forEachIndexed { i, (_, p) -> out.appendLine("        $i => $name::C$i${p?.let { "(${read(it.second, c)})" } ?: ""},") }
                    out.appendLine("        d => return Err(bad_discriminant(\"Variant\", d, $count)),")
                    out.appendLine("    })")
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn write_t$index(w: &mut Vec<u8>, v: &$name, cx: &mut Cx<'_>) -> Result<()> {")
                    out.appendLine("    match v {")
                    cases.forEachIndexed { i, (_, p) ->
                        if (p == null) {
                            out.appendLine("        $name::C$i => write_discriminant(w, $count, $i),")
                        } else {
                            out.appendLine("        $name::C$i(p) => { write_discriminant(w, $count, $i); ${write(p.second, "p", c)} }")
                        }
                    }
                    out.appendLine("    }")
                    out.appendLine("    Ok(())")
                    out.appendLine("}")
                }
                is WitTypeDefKind.Enum -> {
                    val count = kind.cases.size
                    val repr = if (count <= 256) "u8" else if (count <= 65536) "u16" else "u32"
                    out.appendLine()
                    out.appendLine("/// WIT `enum $witName`")
                    out.appendLine("#[derive(ComponentType, Lift, Lower, Clone, Copy)]")
                    out.appendLine("#[component(enum)]")
                    out.appendLine("#[repr($repr)]")
                    out.appendLine("pub enum $name {")
                    kind.cases.forEachIndexed { i, case -> out.appendLine("    #[component(name = \"${esc(case.name)}\")]\n    C$i,") }
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn read_t$index(r: &mut Reader<'_>, cx: &mut Cx<'_>) -> Result<$name> {")
                    out.appendLine("    Ok(match read_discriminant(r, $count)? {")
                    kind.cases.indices.forEach { i -> out.appendLine("        $i => $name::C$i,") }
                    out.appendLine("        d => return Err(bad_discriminant(\"Enum\", d, $count)),")
                    out.appendLine("    })")
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn write_t$index(w: &mut Vec<u8>, v: &$name, cx: &mut Cx<'_>) -> Result<()> {")
                    out.appendLine("    write_discriminant(w, $count, *v as usize);")
                    out.appendLine("    Ok(())")
                    out.appendLine("}")
                }
                is WitTypeDefKind.Flags -> {
                    val count = kind.flags.size
                    if (count == 0) throw Unsupported("flags without flags")
                    val words = if (count <= 16) 1 else (count + 31) / 32
                    out.appendLine()
                    out.appendLine("// WIT `flags $witName`")
                    out.appendLine("flags! {")
                    out.appendLine("    $name {")
                    kind.flags.forEachIndexed { i, f -> out.appendLine("        #[component(name = \"${esc(f.name)}\")]\n        const F$i;") }
                    out.appendLine("    }")
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn read_t$index(r: &mut Reader<'_>, cx: &mut Cx<'_>) -> Result<$name> {")
                    out.appendLine("    let words = read_flag_words::<$words>(r, $count)?;")
                    out.appendLine("    let mut v = $name::empty();")
                    kind.flags.indices.forEach { i -> out.appendLine("    if words[${i / 32}] & (1 << ${i % 32}) != 0 { v |= $name::F$i; }") }
                    out.appendLine("    Ok(v)")
                    out.appendLine("}")
                    out.appendLine()
                    out.appendLine("fn write_t$index(w: &mut Vec<u8>, v: &$name, cx: &mut Cx<'_>) -> Result<()> {")
                    out.appendLine("    write_flag_words(w, $count, &v.as_array());")
                    out.appendLine("    Ok(())")
                    out.appendLine("}")
                }
                else -> error("not a named type: ${def.kind}")
            }
        } catch (e: Unsupported) {
            definedTypes -= index
            throw e
        } finally {
            context = outer
        }
        typeDefs.append(out)
    }

    private fun esc(s: String) = s.replace("\\", "\\\\").replace("\"", "\\\"")
}
