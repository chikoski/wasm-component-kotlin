package wasm2kt.tooling

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import wasm2kt.ast.WitResolve
import wasm2kt.generator.NamingConventions
import wasm2kt.generator.WitToKotlinPoetConverter
import java.nio.file.Files
import java.nio.file.Path

/** Generates the Kotlin sources for a component built with the Chicory backend. */
object ComponentCodegen {
    /**
     * Writes into [outputDir]:
     * - the WIT bindings (worlds, types, `WitSupport.kt`) from the decomposer's `wit.json`, without
     *   the Wasmtime sessions so the result has no native or `java.lang.foreign` dependency;
     * - `<Name>Component`, a [wasm2kt.runtime.ComponentBackendFactory] wiring the AOT-compiled core
     *   modules to the plan, to pass to `<World>.withSession(...)`.
     */
    fun generate(
        decomposedDir: Path,
        outputDir: Path,
        componentName: String,
        packageName: String,
        compiled: List<CoreModuleCompiler.Compiled>,
        planResource: String,
        worldName: String? = null,
    ) {
        val resolve = WitResolve.parse(Files.readString(decomposedDir.resolve("wit.json")))
        WitToKotlinPoetConverter(
            resolve = resolve,
            targetPackage = packageName,
            targetWorldName = worldName,
            emitWasmtimeSessions = false,
        ).generate().forEach { it.writeTo(outputDir) }

        componentFile(componentName, packageName, compiled, planResource).writeTo(outputDir)
    }

    fun componentObjectName(componentName: String): String = NamingConventions.toPascalCase(componentName) + "Component"

    private fun componentFile(
        componentName: String,
        packageName: String,
        compiled: List<CoreModuleCompiler.Compiled>,
        planResource: String,
    ): FileSpec {
        val objectName = componentObjectName(componentName)
        val self = ClassName(packageName, objectName)
        val chicoryComponent = ClassName("wasm2kt.runtime.chicory", "ChicoryComponent")
        val componentPlan = ClassName("wasm2kt.runtime.chicory", "ComponentPlan")
        val coreModule = ClassName("wasm2kt.runtime.chicory", "CoreModule")
        val parser = ClassName("com.dylibso.chicory.wasm", "Parser")
        val factory = ClassName("wasm2kt.runtime", "ComponentBackendFactory")
        val backend = ClassName("wasm2kt.runtime", "ComponentBackend")
        val dispatcher = ClassName("wasm2kt.runtime", "WitHostImportDispatcher").copy(nullable = true)

        val modules = CodeBlock.builder().add("mapOf(\n").indent()
        for (c in compiled.sortedBy { it.index }) {
            modules.add(
                "%L to %T(%T.parse(resource(%S)), { instance -> %T(instance) }),\n",
                c.index, coreModule, parser, c.metaResource, ClassName.bestGuess(c.machineClassName),
            )
        }
        modules.unindent().add(")")

        val type = TypeSpec.objectBuilder(objectName)
            .addKdoc(
                "The `%L` WebAssembly component, generated by wasm2kt. Its core modules were compiled to JVM bytecode " +
                    "at build time and run on Chicory.\n\nPass it to a world's `withSession`/`openSession`; every call to " +
                    "[instantiate] creates an independent component instance.\n",
                componentName,
            )
            .addSuperinterface(factory)
            .addProperty(
                PropertySpec.builder("component", chicoryComponent, KModifier.PRIVATE)
                    .delegate(
                        CodeBlock.builder()
                            .beginControlFlow("lazy")
                            .add("%T(\n", chicoryComponent).indent()
                            .add("%T.parse(String(resource(%S), Charsets.UTF_8)),\n", componentPlan, planResource)
                            .add(modules.build()).add(",\n")
                            .unindent().add(")\n")
                            .endControlFlow()
                            .build(),
                    )
                    .build(),
            )
            .addFunction(
                FunSpec.builder("instantiate")
                    .addModifiers(KModifier.OVERRIDE)
                    .addParameter(ParameterSpec.builder("imports", dispatcher).build())
                    .returns(backend)
                    .addStatement("return component.instantiate(imports)")
                    .build(),
            )
            .addFunction(
                FunSpec.builder("resource")
                    .addModifiers(KModifier.PRIVATE)
                    .addParameter("path", String::class)
                    .returns(ByteArray::class)
                    .addStatement(
                        "return requireNotNull(%T::class.java.getResourceAsStream(path)) { %P }.use { it.readBytes() }",
                        self,
                        "Missing wasm2kt resource \$path; is the generated component jar on the classpath?",
                    )
                    .build(),
            )
            .build()
        return FileSpec.builder(packageName, objectName).addType(type).build()
    }
}

/**
 * The whole build-time pipeline for one component, as the Gradle plugin runs it (split across
 * cacheable tasks there). Handy for tests and other build tools.
 */
object ComponentBuild {
    class Output(val kotlinDir: Path, val classesDir: Path, val resourcesDir: Path)

    fun run(component: Path, componentName: String, packageName: String, workDir: Path, worldName: String? = null): Output {
        val decomposed = workDir.resolve("decomposed")
        val classes = workDir.resolve("classes")
        val resources = workDir.resolve("resources")
        val kotlin = workDir.resolve("kotlin")
        Decomposer.decompose(component, decomposed)
        val internalPackage = internalPackage(packageName, componentName)
        val compiled = CoreModuleCompiler.compile(decomposed, classes, resources, internalPackage)
        val planResource = copyPlan(decomposed, resources, internalPackage)
        ComponentCodegen.generate(decomposed, kotlin, componentName, packageName, compiled, planResource, worldName)
        return Output(kotlin, classes, resources)
    }

    /** Package holding a component's compiled core modules and plan, kept apart per component. */
    fun internalPackage(packageName: String, componentName: String): String =
        "$packageName.wasm2kt." + componentName.lowercase().replace(Regex("[^a-z0-9]+"), "_").trim('_')

    /** Copies `plan.json` next to the `.meta` files and returns its classpath resource name. */
    fun copyPlan(decomposedDir: Path, resourcesDir: Path, internalPackage: String): String {
        val rel = internalPackage.replace('.', '/') + "/plan.json"
        val target = resourcesDir.resolve(rel)
        Files.createDirectories(target.parent)
        Files.copy(decomposedDir.resolve("plan.json"), target, java.nio.file.StandardCopyOption.REPLACE_EXISTING)
        return "/$rel"
    }
}
